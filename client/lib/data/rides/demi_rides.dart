  static RideResponse _ride({
    required int index,
    required ServiceCategory category,
    required PricingMode pricingMode,
    required RideStatus status,
    required String pickupPlace,
    required String pickupAddress,
    required String pickupCity,
    required double pickupLatitude,
    required double pickupLongitude,
    required String dropoffPlace,
    required String dropoffAddress,
    required String dropoffCity,
    required double dropoffLatitude,
    required double dropoffLongitude,
    required double? finalPrice,
    required DateTime createdAt,
    ServiceType serviceType = ServiceType.cityRide,
    DateTime? acceptedAt,
    DateTime? completedAt,
    DateTime? cancelledAt,
    String? cancellationReason,
  }) {
    final rideId = _id('10000000-0000-4000-8000', index);
    final pickup = _stop(
      id: _id('20000000-0000-4000-8000', index),
      serviceRequestId: rideId,
      sequenceOrder: 1,
      stopType: StopType.pickup,
      placeName: pickupPlace,
      address: pickupAddress,
      city: pickupCity,
      latitude: pickupLatitude,
      longitude: pickupLongitude,
    );
    final dropoff = _stop(
      id: _id('30000000-0000-4000-8000', index),
      serviceRequestId: rideId,
      sequenceOrder: 2,
      stopType: StopType.dropoff,
      placeName: dropoffPlace,
      address: dropoffAddress,
      city: dropoffCity,
      latitude: dropoffLatitude,
      longitude: dropoffLongitude,
    );

    return RideResponse(
      id: rideId,
      passengerId: '00000000-0000-4000-8000-000000000101',
      assignedDriverId:
          status == RideStatus.created || status == RideStatus.matching
              ? null
              : _id('40000000-0000-4000-8000', index),
      serviceType: serviceType,
      category: category,
      pricingMode: pricingMode,
      status: status,
      baselineMinPrice: finalPrice == null ? null : finalPrice * 0.9,
      baselineMaxPrice: finalPrice == null ? null : finalPrice * 1.15,
      finalPrice: finalPrice,
      passengerPaymentMethod: PassengerPaymentMethod.cash,
      passengerPaymentMethodId: null,
      paymentCollectionMode: PaymentCollectionMode.driverCollected,
      scheduledAt: null,
      isScheduled: false,
      isRisky: false,
      autoAcceptDriver: false,
      acceptedAt: acceptedAt,
      completedAt: completedAt,
      cancelledAt: cancelledAt,
      cancellationReason: cancellationReason,
      createdAt: createdAt,
      stops: [pickup, dropoff],
      proofImages: const [],
      verificationCodes: const [],
      pickupStop: pickup,
      dropoffStop: dropoff,
    );
  }

  static StopResponse _stop({
    required String id,
    required String serviceRequestId,
    required int sequenceOrder,
    required StopType stopType,
    required String placeName,
    required String address,
    required String city,
    required double latitude,
    required double longitude,
  }) {
    return StopResponse(
      id: id,
      serviceRequestId: serviceRequestId,
      sequenceOrder: sequenceOrder,
      stopType: stopType,
      latitude: latitude,
      longitude: longitude,
      placeName: placeName,
      addressLine1: address,
      addressLine2: null,
      city: city,
      state: 'Punjab',
      country: 'Pakistan',
      postalCode: null,
      contactName: null,
      contactPhone: null,
      instructions: null,
      arrivedAt: null,
      completedAt: null,
    );
  }

  static String _id(String prefix, int index) {
    return '$prefix-${index.toString().padLeft(12, '0')}';
  }
